package first;

public class Typecasting {
    public static void main(String[] args){

        byte b = 24;
        short s = 1;
        int i = 1232;
        long l = 1234424533L;
        float f = 13.14f;
        double d = 12.3333223;
        char c = 'k';
        double result = (b*c) + (s+i) +(l/b)+(f*d);
        System.out.println(result);
    }

}
